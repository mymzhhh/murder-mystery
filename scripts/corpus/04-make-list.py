# -*- coding: utf-8 -*-
"""从普查 CSV 生成《合格清单》markdown（v2：按线索可得性分组）。

为什么分组（2026-10-19 实测）：70 个 A 档里只有 22 个把线索单独存成 docx，
其余线索在图片/PDF 里（商业本习惯把线索做成印刷卡）。而"线索怎么编号、怎么分轮、
怎么藏隐藏线索"恰恰是蒸馏的核心内容之一 —— 所以这 22 个才是**第一优先**。
"""
import csv
import io
from collections import Counter

CSV = r"C:\cluade code\ppt\text-gen-agent\docs\剧本语料-合格清单.csv"
MD = r"C:\cluade code\ppt\text-gen-agent\docs\剧本语料-合格清单.md"

rows = list(csv.DictReader(io.open(CSV, encoding="utf-8-sig")))
tc = Counter(r["档位"] for r in rows)
by = {}
for r in rows:
    by.setdefault(r["档位"], []).append(r)

# 重复本（按内容指纹查出来的，见 docs/剧本语料-重复本.csv）
DUP_CSV = r"C:\cluade code\ppt\text-gen-agent\docs\剧本语料-重复本.csv"
dups = []
try:
    for d in csv.DictReader(io.open(DUP_CSV, encoding="utf-8-sig")):
        dups.append(d)
except FileNotFoundError:
    pass
dup_groups = {}
for d in dups:
    dup_groups.setdefault(d["指纹"], []).append(d)
skip = {d["剧本"] for d in dups if d["建议"].startswith("重复")}

L = []
A = L.append


def mark(r, k):
    return "✓" if r.get(k) == "1" else "—"


def i(r, k):
    try:
        return int(r.get(k) or 0)
    except ValueError:
        return 0


a_all = by.get("A", [])
a1 = [r for r in a_all if i(r, "线索文件字数") > 0 and r["标题"] not in skip]
a1.sort(key=lambda r: (-i(r, "评分"), -i(r, "角色本中位字数")))
a2 = [r for r in a_all if i(r, "线索文件字数") == 0 and r["标题"] not in skip]

A("# 剧本语料合格清单（剧本杀剧本资源合集）")
A("")
A("> 生成时间：2026-10-19　｜　对象：`D:\\play game\\剧本杀剧本资源合集`（24 GB / 10489 个文件 / 225 个剧本）")
A("> 方式：**只读结构**（文件格式 + docx 文本 + PDF 页数/是否可抽中文），未做全文解析。")
A("> 完整明细（225 行 × 27 列）：[剧本语料-合格清单.csv](./剧本语料-合格清单.csv)")
A("> 重复本明细：[剧本语料-重复本.csv](./剧本语料-重复本.csv)")
A("")
A("## 一、结论先说")
A("")
A("| 档位 | 含义 | 数量 | 明天要不要碰 |")
A("|---|---|---|---|")
A(f"| **A1** | docx 文本 + **线索也是 docx** | **{len(a1)}** | **★ 明天先吃这批** |")
A(f"| A2 | docx 文本，但线索在图片/PDF 里 | {len(a2)} | 次优先（能蒸角色本/真相，线索要另找） |")
A(f"| A- | 仅 .doc 旧格式 | {tc.get('A-', 0)} | 转 docx 即可，顺手做 |")
A(f"| B | 文本型 PDF | {tc.get('B', 0)} | 需 MinerU 解析，v0 之后补 |")
A(f"| C | 扫描 PDF | {tc.get('C', 0)} | 需 OCR，成本高 |")
A(f"| D | 纯图片 | {tc.get('D', 0)} | 需 OCR + 碎片多 |")
A(f"| X | 不合格 | {tc.get('X', 0)} | 放弃 |")
A("")
A(f"**建议**：明天只做 **A1 的 {len(a1)} 个** —— 已经覆盖 4–6 人本、分幕本、有真相解析的本，")
A("够出 skill v0 的全部结构分布。别一开始就铺 225 个。")
A("")
A("## 二、判定口径（踩过坑才定的，别误用）")
A("")
A("| 信号 | 口径 |")
A("|---|---|")
A("| 角色本份数 | 非「线索/真相/主持人/手册」命名的 docx，且 ≥1500 字 |")
A("| 角色本中位字数 | 各角色本字数的中位数（对标真本 344 的 5713） |")
A("| 线索条目数 | 《线索.docx》里 `1.` `2.` 编号行数 —— **只认一种排版** |")
A("| 线索文件字数 | 线索类 docx 的总字数 —— **与排版无关，更可靠** |")
A("| 线索轮次数 | 「第N轮…线索」出现几种轮次（344 是 2 轮，039 是 6 轮秘密线索） |")
A("| 分幕 / 手册 / 真相 | 有【第N幕】/ 有 组织者·主持人·手册 / 有 真相·复盘·解析 |")
A("")
A("> ⚠️ **一个被推翻的判据**：最初我用「A1/B1 线索编号」当质量信号，全库都是 0。")
A("> 查 344 的源 docx 才发现：**源剧本根本没有编号** ——《线索.docx》是按人物分组的")
A("> 「1. 2. 3.」列表，`A1` 是我自己导入时编的。判据必须换成语料自带的信号。")
A("")
A("## 三、A1 档：线索也在 docx 里（明天先吃这 22 个）")
A("")
A("| # | 剧本 | 角色 | 角色本 | 中位字 | 线索字 | 轮次 | 隐藏 | 分幕 | 手册 | 真相 | 评分 |")
A("|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in a1:
    A(f"| {r['序号']} | {r['标题']} | {r['角色数'] or '—'} | {r['角色本数']} | {r['角色本中位字数']} | "
      f"{r['线索文件字数']} | {r['线索轮次数']} | {r['隐藏线索标记']} | "
      f"{mark(r, '有分幕')} | {mark(r, '有DM手册')} | {mark(r, '有真相解析')} | {r['评分']} |")
A("")
A("**读表提示**：")
A("")
A("- `中位字 ≥ 3000` 才算读本够厚（344 是 5713）；`线索字 1000–3000` 大致对应 20–50 条线索")
A("- `隐藏 = 0` 不代表没有隐藏线索，可能用「深入调查」「支线线索」等其他叫法")
A("- 角色数看括号里写的，如 `4-5` 表示 4–5 人可开")
A("")
A("## 四、A2 档：docx 文本齐全，但线索在图片/PDF 里")
A("")
A(f"共 **{len(a2)}** 个。角色本与真相解析可读，**线索要另找**（多半是印刷卡图片）。")
A("只列评分前 20；全部见 CSV。")
A("")
A("| # | 剧本 | 角色 | 角色本 | 中位字 | 手册 | 真相 | 评分 |")
A("|---|---|---|---|---|---|---|---|")
for r in a2[:20]:
    A(f"| {r['序号']} | {r['标题']} | {r['角色数'] or '—'} | {r['角色本数']} | {r['角色本中位字数']} | "
      f"{mark(r, '有DM手册')} | {mark(r, '有真相解析')} | {r['评分']} |")
A("")
A("## 五、A- 档：仅 .doc 旧格式（转一下就能用）")
A("")
A("内容齐全，只是 Word 97-2003 二进制格式，python-docx 读不了。")
A("用 LibreOffice 批量转 docx 后即并入 A 档统计。")
A("")
A("| # | 剧本 | 角色 | .doc 数 |")
A("|---|---|---|---|")
for r in by.get("A-", []):
    A(f"| {r['序号']} | {r['标题']} | {r['角色数'] or '—'} | {r['doc']} |")
A("")
A("## 六、B 档：文本型 PDF（MinerU 可直接转 markdown）")
A("")
b_all = by.get("B", [])
A(f"共 **{len(b_all)}** 个，PDF 里能直接抽出中文（非扫描件）。")
A("本地 MinerU 已在 `127.0.0.1:8000` 运行（`D:\\mineru-home`，模型含 MinerU-4 ONNX + 2.5-Pro），")
A("接口 `POST /v1/file_parse` 支持一次最多 100 个文件，输出 markdown。")
A("")
A("| # | 剧本 | 角色 | PDF 数 | 总页数 | 评分 |")
A("|---|---|---|---|---|---|")
for r in b_all:
    A(f"| {r['序号']} | {r['标题']} | {r['角色数'] or '—'} | {r['pdf']} | {r['pdf页数']} | {r['评分']} |")
A("")
A("## 七、C / D 档：要 OCR，最后再说")
A("")
A(f"- **C（扫描 PDF）{tc.get('C', 0)} 个**：整本拍图封装，必须 OCR")
A(f"- **D（纯图片）{tc.get('D', 0)} 个**：只有 jpg/png，多半是线索卡碎片")
A("")
A("这一档里有 100 MB 级的大 PDF（如 `286-白guan` 主持人手册 102 MB），解析慢且")
A("OCR 错字会污染统计。**不建议作为第一批语料。**")
A("")
A("## 八、不合格（X 档，5 个）")
A("")
for r in by.get("X", []):
    A(f"- `{r['标题']}` —— {r['判定理由']}")
A("")

A(f"## 八之二、重复本（去重后有效 {len(rows) - len(skip)} 个）")
A("")
A(f"按「文件名+大小」指纹比对，有 {len(dup_groups)} 组内容完全相同的本，可跳过 {len(skip)} 个：")
A("")
A("| 保留 | 可跳过 |")
A("|---|---|")
for h, g in dup_groups.items():
    keep = [x["剧本"] for x in g if x["建议"].startswith("保留")]
    drop = [x["剧本"] for x in g if x["建议"].startswith("重复")]
    A("| " + (keep[0] if keep else "—") + " | " + ("、".join(drop) if drop else "—") + " |")
A("")
A("## 九、明天怎么用（可执行）")
A("")
A("| 步骤 | 动作 | 预计 |")
A("|---|---|---|")
A("| 1 | 取 A1 的 21 个，docx → 统一 markdown（每本一文件，保留章节层级） | 1 h |")
A("| 2 | 跑量化：角色本字数分布、线索条数/轮次、时间线条数、地点数、真相字数、图片引用数 | 30 min |")
A("| 3 | 出 skill v0：SKILL.md + references/分布表 + scripts/校验器 | 2 h |")
A("| 4 | 留出 2 本不参与蒸馏，生成 1 本对比打分 | 2 h |")
A("| 5 | 顺手把 A- 的 9 个 .doc 批量转 docx（LibreOffice） | 15 min |")
A("")
A("B 档放在 v0 之后：用 30 个文本型 PDF 验证「分布是否稳定」，再决定要不要扩到 C/D。")
A("")
A("## 十、已知局限（明天别当定论）")
A("")
A("1. **PDF 只看了前 2 页**判断是否可抽中文，个别本可能 B/C 误判")
A("2. **D 档 53 个未抽样核实**，里面可能混着完整扫描本（建议抽 3 个看看）")
A("3. **线索真伪未读正文**：`线索条目数`/`线索文件字数` 只说明「有线索文件」，不保证线索完整")
A("4. **角色本份数偏低**：多角色写进一个 docx 的本会被算成 1 份；只写供词的短本也会被 1500 字阈值漏掉（如 008-死亡致意，角色本是「XX 供词.docx」，只有几百字，被判成 0 份）")
A("5. **未做内容质量判断**（是否本格推理、诡计是否成立、有无逻辑硬伤）—— 必须读正文后才能判")
A("")

io.open(MD, "w", encoding="utf-8").write("\n".join(L))
print("已写出:", MD, "行数:", len(L))
print(f"A1={len(a1)} A2={len(a2)} A-={tc.get('A-', 0)} B={tc.get('B', 0)} C={tc.get('C', 0)} D={tc.get('D', 0)} X={tc.get('X', 0)}")
